def main() -> None:
    conn = psycopg2.connect(
        host=os.getenv("POSTGRES_HOST", "quantmind-db"),
        port=int(os.getenv("POSTGRES_PORT", "5432")),
        user=os.getenv("POSTGRES_USER", "quantmind"),
        password=os.getenv("POSTGRES_PASSWORD", "quantmind2026"),
        dbname=os.getenv("POSTGRES_DB", "quantmind"),
    )
    rows: list[tuple[str, str, str, float, bool]] = []
    seen: set[tuple[str, str]] = set()
    for term, tag in ENTITIES:
        key = (term, "event")
        if key in seen:
            continue
        seen.add(key)
        rows.append((term, "event", tag, 1.0, True))

    sql = """
        INSERT INTO finance_lexicon (term, kind, event_tag, weight, enabled)
        VALUES %s
        ON CONFLICT (term, kind) DO UPDATE SET
            event_tag = EXCLUDED.event_tag,
            weight = EXCLUDED.weight,
            enabled = TRUE;
    """
    with conn.cursor() as cur:
        execute_values(cur, sql, rows, page_size=500)
    conn.commit()
    with conn.cursor() as cur:
        cur.execute(
            "SELECT event_tag, COUNT(*) FROM finance_lexicon "
            "WHERE event_tag IN ('国家','地区','省份','城市','领导人','调研','部门') "
            "GROUP BY event_tag ORDER BY 2 DESC"
        )
        print("实体词分布:")
        for tag, n in cur.fetchall():
            print(f"  {tag:6} {n}")
    conn.close()


if __name__ == "__main__":
    main()
